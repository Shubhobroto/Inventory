CREATE TABLE orders (
    id              UUID PRIMARY KEY,
    idempotency_key VARCHAR(100)  NOT NULL,
    customer_id     VARCHAR(100)  NOT NULL,
    product_id      VARCHAR(100)  NOT NULL,
    quantity        INT           NOT NULL,
    amount          NUMERIC(19,2) NOT NULL,
    order_status    VARCHAR(30)   NOT NULL,
    saga_status     VARCHAR(30)   NOT NULL,
    failure_reason  VARCHAR(200),
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_orders_idempotency_key UNIQUE (idempotency_key)
);

-- Used by the timeout sweep: orders still in progress and idle for a while.
CREATE INDEX idx_orders_saga_updated ON orders (saga_status, updated_at);

CREATE TABLE outbox_events (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_id   UUID         NOT NULL,
    topic        VARCHAR(100) NOT NULL,
    message_key  VARCHAR(100) NOT NULL,
    event_type   VARCHAR(100) NOT NULL,
    payload      TEXT         NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    published_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uq_outbox_message_id UNIQUE (message_id)
);

CREATE INDEX idx_outbox_unpublished ON outbox_events (published_at, id);

CREATE TABLE processed_messages (
    message_id   UUID PRIMARY KEY,
    processed_at TIMESTAMP WITH TIME ZONE NOT NULL
);
