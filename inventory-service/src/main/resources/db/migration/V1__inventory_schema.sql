CREATE TABLE stock (
    product_id VARCHAR(100) PRIMARY KEY,
    available  INT NOT NULL,
    CONSTRAINT ck_stock_not_negative CHECK (available >= 0)
);

-- One row per order: the order id as primary key stops an order from reserving stock twice.
CREATE TABLE reservations (
    order_id   UUID PRIMARY KEY,
    product_id VARCHAR(100),
    quantity   INT         NOT NULL,
    status     VARCHAR(20) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE outbox_events (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_id   UUID         NOT NULL,
    topic        VARCHAR(100) NOT NULL,
    message_key  VARCHAR(100) NOT NULL,
    event_type   VARCHAR(100) NOT NULL,
    payload      TEXT         NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    published_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uq_outbox_message_id UNIQUE (message_id)
);

CREATE INDEX idx_outbox_unpublished ON outbox_events (published_at, id);

CREATE TABLE processed_messages (
    message_id   UUID PRIMARY KEY,
    processed_at TIMESTAMP WITH TIME ZONE NOT NULL
);
