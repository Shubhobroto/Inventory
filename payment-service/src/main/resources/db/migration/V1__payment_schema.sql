CREATE TABLE wallets (
    customer_id VARCHAR(100)  PRIMARY KEY,
    balance     NUMERIC(19,2) NOT NULL,
    CONSTRAINT ck_wallet_not_negative CHECK (balance >= 0)
);

-- One row per order: the order id as primary key means an order is charged at most once.
CREATE TABLE payments (
    order_id    UUID PRIMARY KEY,
    customer_id VARCHAR(100),
    amount      NUMERIC(19,2) NOT NULL,
    status      VARCHAR(20)   NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at  TIMESTAMP WITH TIME ZONE NOT NULL
);

-- Append-only: rows are never updated or deleted.
CREATE TABLE ledger_entries (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id    UUID          NOT NULL,
    customer_id VARCHAR(100)  NOT NULL,
    entry_type  VARCHAR(10)   NOT NULL,
    amount      NUMERIC(19,2) NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_ledger_order_type UNIQUE (order_id, entry_type)
);

CREATE TABLE outbox_events (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_id   UUID         NOT NULL,
    topic        VARCHAR(100) NOT NULL,
    message_key  VARCHAR(100) NOT NULL,
    event_type   VARCHAR(100) NOT NULL,
    payload      TEXT         NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    published_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uq_outbox_message_id UNIQUE (message_id)
);

CREATE INDEX idx_outbox_unpublished ON outbox_events (published_at, id);

CREATE TABLE processed_messages (
    message_id   UUID PRIMARY KEY,
    processed_at TIMESTAMP WITH TIME ZONE NOT NULL
);
